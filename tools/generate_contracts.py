#!/usr/bin/env python3
"""Regenerate wire DTOs from api-sdk-go at the plan's pinned commit.
Usage: python3 tools/generate_contracts.py ../api-sdk-go
Handwritten protocol/validation code is never overwritten.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
go = Path(sys.argv[1]).resolve()
pinned = '2aa0cf1450ca4779e98fe0995adfc00257ea5d15'
if subprocess.check_output(['git', '-C', str(go), 'rev-parse', 'HEAD'], text=True).strip() != pinned:
    raise SystemExit('Reference HEAD differs from pinned commit ' + pinned)
ns = 'WaasApi\\ApiSdkPhp\\V2'
structs = {}
aliases = {}
paths = {}
methods = {}

def parse(file, group, predicate=lambda _: True):
    raw = file.read_text()
    for name, body in re.findall(r'type (\w+) struct \{(.*?)\n\}', raw, re.S):
        if not predicate(name):
            continue
        fields = []
        for line in body.splitlines():
            m = re.match(r'\s*(\w+)\s+(\S+)\s+`json:"([^",]+)(,omitempty)?"`', line)
            if m:
                field, typ, wire, omit = m.groups()
                if wire == '-':
                    continue
                fields.append((field[0].lower() + field[1:], typ, wire, bool(omit)))
            elif line.strip() and not line.strip().startswith('//') and line.strip() != 'Response':
                raise SystemExit('Unparsed field: ' + line)
        structs[group, name] = fields
    for name, shape, typ in re.findall(r'type (\w+) = (ObjectResponse|ListResponse)\[(\w+)\]', raw):
        aliases[name] = ('object' if shape == 'ObjectResponse' else 'list', typ)
    for name, path in re.findall(r'path(\w+)\s+path = "([^"]+)"', raw):
        paths[name] = path
    for name, req, resp in re.findall(r'func \(c \*Client\) (\w+)\(ctx context.Context(?:, request (\w+))?\) \((\w+), error\)', raw):
        methods[name] = (req or 'EmptyRequest', resp)

for f in sorted((go / 'clientv2').glob('*.go')):
    if f.name.endswith('_test.go'):
        continue
    if f.name.startswith('requests'):
        parse(f, 'Request', lambda n: n != 'emptyRequest')
    elif f.name.startswith('responses') and f.name != 'responses.go':
        parse(f, 'Response', lambda n: not n.endswith('Response'))
        # Non-generic string and no-data envelopes.
        for name, body in re.findall(r'type (\w+Response) struct \{(.*?)\n\}', f.read_text(), re.S):
            aliases[name] = ('string', 'string') if 'Data string' in re.sub(r'\s+', ' ', body) else ('none', '')
    elif f.name.startswith('client'):
        parse(f, 'unused', lambda _: False)
for f in ['notify_types.go', 'tr_types.go', 'withdraw_risk_server.go', 'exchange_risk_server.go']:
    parse(go / 'callbackv2' / f, 'Callback', lambda n: n not in ['WithdrawRiskResult', 'ExchangeRiskResult'] and not n.endswith('Config') and n not in ['WithdrawRiskServer','ExchangeRiskServer','riskReview'])
parse(go / 'travelrule/ivms101.go', 'TravelRule\\Ivms101')
# The plan also requires natural-person document/address evidence. The pinned Go
# model omits these standard IVMS101 fields; make them explicit PHP properties
# rather than relying on untyped extension data or deprecated dynamic properties.
structs['TravelRule\\Ivms101', 'NaturalPerson'] += [
    ('nationalIdentification', '*NationalIdentification', 'nationalIdentification', True),
    ('geographicAddress', '[]GeographicAddress', 'geographicAddress', True),
]
structs['Request', 'EmptyRequest'] = []

primitive = {'string':'string', 'int':'int', 'int64':'int64', 'uint64':'int64', 'float64':'number', 'bool':'bool', 'json.RawMessage':'json'}

def mapped(typ, group):
    if typ.startswith('*'):
        return mapped(typ[1:], group)
    if typ.startswith('[]'):
        return 'list:' + mapped(typ[2:], group)
    if typ.startswith('map[string]'):
        return 'map:' + mapped(typ[11:], group)
    if typ in primitive:
        return primitive[typ]
    if (group, typ) not in structs:
        matches = [g for g, n in structs if n == typ]
        if len(matches) != 1:
            raise SystemExit('Unknown type: ' + typ + ' in ' + group)
        group = matches[0]
    return ns + '\\' + group + '\\' + typ

for (group, name), fields in structs.items():
    base = 'RequestDto' if group == 'Request' else 'Callback\\CallbackResponse' if group == 'Callback' and name.endswith('Response') else 'Model'
    php = '<?php\n\nnamespace ' + ns + '\\' + group + ';\n\n'
    php += '// Wire contract: api-sdk-go ' + pinned[:7] + '. Generated by tools/generate_contracts.py.\n'
    php += 'class ' + name + ' extends \\' + ns + '\\' + base + '\n{\n    const FIELDS = [\n'
    for prop, typ, wire, omit in fields:
        t = mapped(typ, group)
        php += f"        '{wire}' => ['{prop}', '{t}', " + ('false' if omit else 'true') + '],\n'
    php += '    ];\n'
    for prop, typ, wire, omit in fields:
        def phpdoc(t):
            if t.startswith('list:'): return 'array<' + phpdoc(t[5:]) + '>'
            if t.startswith('map:'): return 'array<string, ' + phpdoc(t[4:]) + '>'
            return {'int64': 'int|string', 'number': 'int|float', 'json': 'mixed'}.get(t, ('\\' + t) if '\\' in t else t)
        doc = phpdoc(mapped(typ, group))
        default = 'null'
        # Empty arrays on wire are meaningful, especially beneficiaryPersons.
        if group == 'TravelRule\\Ivms101' and name == 'Beneficiary' and wire == 'beneficiaryPersons':
            default = '[]'
        php += '\n    /** @var ' + doc + '|null */\n    public $' + prop + ' = ' + default + ';\n'
    if group == 'TravelRule\\Ivms101' and name == 'Beneficiary':
        php += '''
    #[\\ReturnTypeWillChange]
    public function jsonSerialize()
    {
        $payload = parent::jsonSerialize();
        if ($payload->beneficiaryPersons === null) {
            $payload->beneficiaryPersons = [];
        }
        return $payload;
    }
'''
    if name == 'TrHealthCallbackResponse':
        php += '''
    public $healthy = false;
    public $msg = '';

    public function __construct($values = [])
    {
        $values = (array) $values;
        $this->healthy = isset($values['healthy']) ? $values['healthy'] : false;
        $this->msg = isset($values['msg']) ? $values['msg'] : '';
        unset($values['healthy'], $values['msg']);
        parent::__construct($values);
    }
'''
    if name == 'TrTransferRequest':
        php += '''
    public function setThreshold(TrThresholdDeclaration $declaration)
    {
        $this->threshold = $declaration;
        $this->omit('is_exceeding_threshold');
        return $this;
    }

    public function setThresholdExceeded($exceeded)
    {
        if (!is_bool($exceeded)) {
            throw new \\InvalidArgumentException('exceeded must be boolean');
        }
        $this->isExceedingThreshold = $exceeded;
        $this->omit('threshold');
        return $this;
    }
'''
    php += '}\n'
    dest = root / 'src/V2' / group.replace('\\', '/') / (name + '.php')
    dest.write_text(php)

for name, (shape, typ) in aliases.items():
    t = mapped(typ, 'Response') if typ else ''
    php = f'''<?php
namespace {ns}\\Response;

// Wire contract: api-sdk-go {pinned[:7]}.
class {name} extends \\{ns}\\ApiResponse
{{
    const SHAPE = '{shape}';
    const DATA_TYPE = '{t}';
}}
'''
    (root / 'src/V2/Response' / (name + '.php')).write_text(php)

assert len(methods) == len(paths) == len(aliases) == 42, (len(methods), len(paths), len(aliases))
client = '''<?php
namespace WaasApi\\ApiSdkPhp\\V2;

/** The 42 public V2 methods; all transport and signature handling lives in ClientBase. */
final class Client extends ClientBase
{
'''
for name, (req, resp) in methods.items():
    method = name[0].lower() + name[1:]
    optional = req == 'EmptyRequest' or all(x[3] for x in structs['Request', req])
    default = ' = null' if optional else ''
    initialization = f'        if ($request === null) {{ $request = new Request\\{req}(); }}\n' if optional else ''
    argument_type = '' if optional else f'Request\\{req} '
    if optional:
        initialization += f'        if (!$request instanceof Request\\{req}) {{ throw new \\InvalidArgumentException("Expected {req}"); }}\n'
    client += f'''
    /** @param Request\\{req}|null $request @return Response\\{resp} */
    public function {method}({argument_type}$request{default})
    {{
{initialization}        return $this->call('{paths[name]}', $request, Response\\{resp}::class);
    }}
'''
client += '}\n'
(root / 'src/V2/Client.php').write_text(client)
# Independent platform fixtures and literal paths, retained for offline tests.
for source, target in [('crypto/testdata/signature_v2_fixture.json','signature_v2_fixture.json'), ('clientv2/testdata/response_data.json','response_data.json')]:
    (root / 'tests/Fixtures' / target).write_bytes((go/source).read_bytes())
fixture = (go/'crypto/codevasp_test.go').read_text()
crypto = dict(re.findall(r'(fixture\w+)\s*=\s*"([^"]*)"',fixture))
crypto['fixturePlaintext'] = re.search(r'fixturePlaintext\s*=\s*`([^`]+)`',fixture)[1]
(root/'tests/Fixtures/codevasp.json').write_text(json.dumps(crypto, indent=2)+'\n')
(root/'tests/Fixtures/endpoints.json').write_text(json.dumps({n[0].lower()+n[1:]:{'path':paths[n],'request':r,'response':s} for n,(r,s) in methods.items()}, indent=2)+'\n')
print(f'Generated {len(structs)} DTOs, {len(aliases)} response envelopes and {len(methods)} client methods.')
